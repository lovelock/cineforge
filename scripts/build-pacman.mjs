import { execFileSync } from 'node:child_process';
import { chmod, cp, mkdir, readFile, rename, rm, stat, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = fileURLToPath(new URL('..', import.meta.url));
const appDir = join(repoRoot, 'apps/electron');
const release = join(appDir, 'release');
const unpacked = join(release, 'linux-unpacked');
const stage = join(release, 'pacman-stage');

const pkg = JSON.parse(await readFile(join(appDir, 'package.json'), 'utf8'));
const version = String(pkg.version).replace(/-/g, '_');
const arch = 'x86_64';
const pkgrel = 1;
const fileName = `cineforge-${version}-${pkgrel}-${arch}.pkg.tar.zst`;
const output = join(release, fileName);

try {
  await stat(join(unpacked, 'cineforge'));
} catch {
  console.error(`缺少 ${unpacked}/cineforge，请先运行 electron-builder --linux dir`);
  process.exit(1);
}

await rm(stage, { recursive: true, force: true });
await rm(output, { force: true });
await mkdir(join(stage, 'opt'), { recursive: true });
await mkdir(join(stage, 'usr/share/applications'), { recursive: true });
await mkdir(join(stage, 'usr/share/icons/hicolor/512x512/apps'), { recursive: true });

await cp(unpacked, join(stage, 'opt/cineforge'), { recursive: true });
await cp(join(appDir, 'icon.png'), join(stage, 'usr/share/icons/hicolor/512x512/apps/cineforge.png'));
try {
  await chmod(join(stage, 'opt/cineforge/chrome-sandbox'), 0o4755);
} catch {
  // chrome-sandbox may be absent in some Electron builds
}

await writeFile(join(stage, 'usr/share/applications/cineforge.desktop'), `[Desktop Entry]
Name=影匠
Comment=影匠 Cineforge — 调用本机 ffmpeg 的音视频格式转换器
Exec=/opt/cineforge/cineforge %U
Icon=cineforge
Terminal=false
Type=Application
Categories=AudioVideo;
StartupWMClass=cineforge
`, 'utf8');

const installedSize = Number(
  execFileSync('du', ['-sb', join(stage, 'opt'), join(stage, 'usr')], { encoding: 'utf8' })
    .split('\n')
    .filter(Boolean)
    .reduce((sum, line) => sum + Number(line.split('\t')[0] ?? 0), 0),
);

const depends = [
  'ffmpeg',
  'gtk3',
  'nss',
  'libnotify',
  'libxss',
  'libxtst',
  'xdg-utils',
  'at-spi2-core',
  'libsecret',
  'alsa-lib',
  'mesa',
  'libcups',
  'libpulse',
  'libxcomposite',
  'libxdamage',
  'libxrandr',
  'util-linux-libs',
];

const pkginfo = [
  '# Generated by Cineforge packaging script',
  'pkgname = cineforge',
  'pkgbase = cineforge',
  `pkgver = ${version}-${pkgrel}`,
  `pkgdesc = ${pkg.description}`,
  `url = ${pkg.homepage}`,
  `builddate = ${Math.floor(Date.now() / 1000)}`,
  `packager = ${pkg.author}`,
  `size = ${installedSize}`,
  `arch = ${arch}`,
  'license = custom',
  ...depends.map((dep) => `depend = ${dep}`),
  'xdata = pkgtype=pkg',
  '',
].join('\n');

await writeFile(join(stage, '.PKGINFO'), pkginfo, 'utf8');

const mtreeTmp = join(release, '.MTREE.tmp');
execFileSync('bsdtar', [
  '-C', stage,
  '--uid', '0',
  '--gid', '0',
  '-czf', mtreeTmp,
  '--format=mtree',
  '--options', '!all,use-set,type,uid,gid,mode,time,size,md5,sha256,link',
  '--exclude', '.MTREE',
  '.',
]);
await rename(mtreeTmp, join(stage, '.MTREE'));

const tarTmp = join(release, '.pacman.tar');
execFileSync('bsdtar', [
  '-C', stage,
  '--uid', '0',
  '--gid', '0',
  '-cf', tarTmp,
  '.PKGINFO',
  '.MTREE',
  'opt',
  'usr',
]);
execFileSync('zstd', ['-19', '-T0', '--force', '-o', output, tarTmp]);

await rm(stage, { recursive: true, force: true });
await rm(tarTmp, { force: true });
await rm(mtreeTmp, { force: true });

console.log(`built ${output}`);
